export type Riwaya = 'hafs' | 'warsh' | 'qaloon' | 'doori' | 'shuba' | 'soosi'

// Garde de validation d'un paramètre riwaya (URL, stockage…)
export function versRiwaya(v?: string | null): Riwaya {
    return v === 'warsh' || v === 'qaloon' || v === 'doori' || v === 'shuba' || v === 'soosi' ? v : 'hafs'
}

const cache: Record<string, any> = {}

export function getSourate(index: number, riwaya: Riwaya = 'hafs') {
    const cle = `${riwaya}:${index}`
    if (cache[cle]) return cache[cle]
    const loader = (
        riwaya === 'warsh' ? fichiersWarsh :
        riwaya === 'qaloon' ? fichiersQaloon :
        riwaya === 'doori' ? fichiersDoori :
        riwaya === 'shuba' ? fichiersShuba :
        riwaya === 'soosi' ? fichiersSoosi :
        fichiers
    )[index]
    if (!loader) return null
    const data = loader()
    cache[cle] = data
    return data
}
